#!/usr/bin/env python3
"""Check that the hand-written tests in aux/macros_test.xml can run.

`aux/macros_test.xml` (the `manutest_*` macros) and its fixture recipes in
`prepare_test_data_manual.sh` are the only hand-maintained test material; every
file they reference has to exist in `test-data/`.  Upstream renames fixtures
(and drops the class-test data files which used to be shipped), so a recipe can
silently rot - and because the autogenerated tests are the ones under watch,
nobody notices.  Three checks:

  * every input of a `prepare_test_data_manual.sh` recipe exists (or is written
    by an earlier recipe) - that is what makes the regeneration log show
    "X failed" lines;
  * every file the `manutest_*` macros reference exists (or is written by a
    recipe) - a missing one turns the wrapper test into an error;
  * the macro's tests are the wrapper's last tests, unchanged.  The generator
    appends them verbatim (it only adds `location=` and assertions), so the
    wrapper is where a drift between the two shows up.  Round 3d raised
    `expect_num_outputs` in the wrappers - exactly this kind of drift: the value
    belongs in the macro, otherwise the next regeneration reverts it.

Usage: check_manual_tests.py [--test-data DIR] [--warn]
Exit code 1 on problems (0 with --warn).
"""
import argparse
import os
import re
import shlex
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
OPENMS = os.path.dirname(os.path.dirname(HERE))

# anything with a short extension is treated as a file name
FILE_RE = re.compile(r"\.[A-Za-z][A-Za-z0-9]{1,9}$")
# recipes write their result into these options (the value is not an input)
OUTPUT_OPTS = {
    "-out",
    "-html",
    "-out_type",
    "-write_ini",
    "-write_ctd",
    "-log",
    "-debug",
}
# options whose value is never a file name
SKIP_OPTS = {"-test", "-threads", "-force", "-best", "-ini_ip"}


def recipes(script):
    """Yield (tool, inputs, outputs) for every tool invocation of the script."""
    for line in open(script, errors="replace"):
        line = line.strip()
        if not line or line.startswith("#") or line.startswith("if "):
            continue
        try:
            tokens = shlex.split(line)
        except ValueError:
            continue
        if not tokens or "=" in tokens[0] or tokens[0].startswith("("):
            continue
        tool, inputs, outputs = tokens[0], [], []
        option = None
        for token in tokens[1:]:
            if token.startswith("-") and not FILE_RE.search(token):
                option = token
                continue
            if "$" in token or "*" in token:
                option = None
                continue
            if not FILE_RE.search(token):
                option = None
                continue
            if option in OUTPUT_OPTS:
                outputs.append(token)
            elif option not in SKIP_OPTS:
                inputs.append(token)
            option = None
        if inputs or outputs:
            yield tool, inputs, outputs


def macro_fixtures(macros):
    """Yield (macro name, file name) for every file reference of a macro."""
    for element in ET.parse(macros).getroot().iter("xml"):
        macro = element.get("name", "")
        for child in element.iter():
            value = child.get("value")
            if not value:
                continue
            for name in value.split(","):
                name = name.strip()
                if FILE_RE.search(name):
                    yield macro, name


def macro_tests(macros):
    """Yield (tool, test element) for every test of a manutest_* macro."""
    for element in ET.parse(macros).getroot().iter("xml"):
        name = element.get("name", "")
        if not name.startswith("manutest_"):
            continue
        for test in element.findall("test"):
            yield name[len("manutest_"):], test


def signature(test):
    """What the generator must not change: outputs and params, in order.

    An output loses its `value=` when it gets an assertion (`location=` names the
    reference then), so only its name is compared.  A `<param>` keeps its value
    and gains `location=` next to it.
    """
    expect = test.get("expect_num_outputs")
    params = [(child.get("name"), child.get("value")) for child in test if child.tag == "param"]
    outputs = [child.get("name") for child in test if child.tag == "output"]
    return expect, params, outputs


def present(name, test_data):
    """A fixture may be listed with a subdirectory (MAPPING/ms-mapping.xml)."""
    return any(
        os.path.exists(os.path.join(test_data, candidate))
        for candidate in (name, os.path.basename(name))
    )


def main(argv=None):
    parser = argparse.ArgumentParser()
    parser.add_argument("--macros", default=os.path.join(OPENMS, "aux", "macros_test.xml"))
    parser.add_argument(
        "--recipes", default=os.path.join(OPENMS, "prepare_test_data_manual.sh")
    )
    parser.add_argument("--test-data", default=os.path.join(OPENMS, "test-data"))
    parser.add_argument("--warn", action="store_true", help="report but exit 0")
    args = parser.parse_args(argv)

    produced = set()
    problems = []

    # 1. the recipes: inputs must exist when the recipe runs
    for tool, inputs, outputs in recipes(args.recipes):
        for name in inputs:
            if not present(name, args.test_data) and name not in produced:
                problems.append(f"recipe {tool}: input {name} does not exist")
        produced.update(outputs)

    # 2. the macros: their fixtures must exist (or be produced by a recipe)
    for macro, name in macro_fixtures(args.macros):
        if not present(name, args.test_data) and name not in produced:
            problems.append(f"{macro}: fixture {name} does not exist")

    # 3. the wrapper carries the macro's tests - at the end, and unchanged
    expected = {}
    for tool, test in macro_tests(args.macros):
        expected.setdefault(tool, []).append(signature(test))
    for tool, macros in expected.items():
        wrapper = os.path.join(OPENMS, f"{tool}.xml")
        if not os.path.exists(wrapper):
            problems.append(f"manutest_{tool}: {tool}.xml does not exist")
            continue
        tests = ET.parse(wrapper).getroot().findall(".//test")
        if len(tests) < len(macros):
            problems.append(
                f"{tool}: {len(macros)} manual test(s), but the wrapper has {len(tests)}"
            )
            continue
        for index, (want, got) in enumerate(zip(macros, map(signature, tests[-len(macros):]))):
            if want != got:
                problems.append(
                    f"{tool}: manual test {index + 1} differs from aux/macros_test.xml\n"
                    f"      macro:   {want}\n      wrapper: {got}"
                )

    print(
        f"manual tests: {len(produced)} fixtures produced, "
        f"{sum(len(tests) for tests in expected.values())} test(s) in "
        f"{len(expected)} wrappers, {len(problems)} problems"
    )
    for problem in problems:
        print(f"  {problem}")
    if not problems:
        return 0
    return 0 if args.warn else 1


if __name__ == "__main__":
    sys.exit(main())
